export function memoryBlock(facts: MemoryFact[]): string {
  if (facts.length === 0) return "Что ты знаешь о пользователе: пока ничего.";
  return `Что ты знаешь о пользователе (номер — для forget):\n${facts.map((f) => `#${f.id} ${f.fact}`).join("\n")}`;
}
