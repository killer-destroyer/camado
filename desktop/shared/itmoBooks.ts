/** Книги ИТМО, подходящие к названию предмета. */
export function booksFor(subject: string): ItmoBook[] {
  const seen = new Set<number>();
  const out: ItmoBook[] = [];
  for (const a of BOOK_AREAS) {
    if (!a.match.test(subject)) continue;
    for (const b of a.books) {
      if (seen.has(b.id)) continue;
      seen.add(b.id);
      out.push(b);
    }
  }
  return out;
}
